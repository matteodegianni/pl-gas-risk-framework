"""Stage 9 report and figure. Every number is computed."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def figure(att: pd.DataFrame, path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(10, 4))
    for c in ["total_pnl", "plan_margin", "volume_effect", "price_effect", "fx_effect"]:
        ax.plot(att.index, att[c].cumsum() / 1e6, lw=1.2 if c == "total_pnl" else 0.9, label=c,
                color="black" if c == "total_pnl" else None)
    ax.axhline(0, color="grey", lw=0.6)
    ax.set_ylabel("cumulative PLN million")
    ax.set_title("SYNTHETIC contract: cumulative P&L and attribution components", fontsize=10)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def write_stage9_report(cfg: Config, tables: dict[str, pd.DataFrame], att: pd.DataFrame) -> None:
    out = cfg.path("outputs_dir")
    (out / "figures").mkdir(exist_ok=True)
    figure(att, out / "figures" / "stage9_attribution.png")
    tot = tables["total"].set_index("component")["pln"]
    c = tables["contract"].iloc[0]
    comps = ["volume_effect", "price_effect", "fx_effect"]
    big = max(comps, key=lambda k: abs(tot[k]))
    text = f"""# Stage 9 - P&L attribution report

Generated by `python -m gasrisk.attribution`. Every number is computed. Contract, volumes and hedges are **synthetic**;
prices are TGE (trade date, in EUR via ECB EUR/PLN), TTF second month held to roll and ECB EUR/PLN.

## Contract (synthetic)

{_md(tables['contract'], floatfmt="{:,.4f}")}

Contracted volumes follow a winter-peak profile summing to {cfg['book']['q_open_mwh']:,} MWh; actual volumes deviate
by a synthetic AR(1) demand factor. Fixed sale price = plan cost (TGE x EUR/PLN at signing) + {cfg['attribution']['sale_margin_pln_mwh']}
PLN/MWh. TTF futures ({cfg['attribution']['ttf_hedge_ratio']:.0%}) and the EUR forward ({cfg['attribution']['fx_hedge_ratio']:.0%}) are sized on the
remaining contracted volume. Deliveries are booked on panel trading days at the TGE trade-date price (simplification).

## Decomposition

Daily P&L = V (S - G F) + N_ttf dTTF F + N_fx dF, split sequentially and exactly:

| component | formula |
|---|---|
| plan margin | C (S - P0 F0) |
| volume effect | (V - C)(S - P0 F0) |
| price effect | -V (G - P0) F0 + N_ttf dTTF F0 |
| FX effect | -V G (F - F0) + N_ttf dTTF (F - F0) + N_fx dF |

The four components sum to the daily P&L with a maximum absolute residual of {c['max_abs_daily_residual']:.3e} PLN
(enforced in code and by `tests/test_attribution.py`).

## Contract-to-date totals

{_md(tables['total'], floatfmt="{:,.0f}")}

Total P&L {tot['total_pnl']:,.0f} PLN against a plan margin of {tot['plan_margin']:,.0f} PLN; the largest deviation from plan is the
**{big.replace('_', ' ')}** ({tot[big]:+,.0f} PLN). Within the price effect, purchases contribute {tot['price_effect_purchase']:+,.0f} PLN and
the TTF hedge {tot['price_effect_hedge']:+,.0f} PLN.

![Attribution](figures/stage9_attribution.png)

## Monthly

{_md(tables['monthly'], floatfmt="{:,.0f}")}

## Limitations

- Contract, demand and hedge sizes are synthetic; the plan cost uses the TGE day-ahead price at signing because
  no TGE forward curve is available.
- Weekend deliveries are folded into trading days; the hedge is rebalanced daily to the remaining volume.
- This realised, delivery-based view differs from the Stage 5 risk view, which holds a constant open volume.
"""
    (out / "stage9_report.md").write_text(text, encoding="utf-8")
