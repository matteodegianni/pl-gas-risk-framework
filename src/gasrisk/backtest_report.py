"""Stage 6 report. Every number and verdict is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage6_report(cfg: Config, tables: dict[str, pd.DataFrame], fc: pd.DataFrame) -> None:
    bt, tl, es, sub = tables["backtest"], tables["traffic_light"], tables["es_check"], tables["by_subperiod"]
    d = fc.dropna(subset=["pnl"])
    passing = bt[bt["pass_cc"]].groupby("level")["method"].apply(list).to_dict()
    all_pass = bt.groupby("method")["pass_cc"].all()
    winners = all_pass[all_pass].index.tolist()
    b99 = bt[bt["level"] == 0.99].set_index("method")
    closest = (b99["observed"] - b99["expected"]).abs().idxmin()
    show = ["method", "level", "n", "expected", "observed", "rate", "lr_pof", "p_pof", "n11", "lr_ind", "p_ind", "lr_cc",
            "p_cc", "pass_pof", "pass_ind", "pass_cc"]
    text = f"""# Stage 6 - VaR backtesting report

Generated by `python -m gasrisk.backtest` from the Stage 5 walk-forward forecasts. Every number and verdict is
computed. The book is **synthetic**; losses are in PLN.

Backtest sample: {len(d) // d['method'].nunique()} days per method, targets {d['target'].min().date()} to {d['target'].max().date()}
(the two TTF roll days excluded in Stage 1 have no realised P&L). An exception is a realised loss above the VaR
forecast made the day before.

## Exceptions, Kupiec and Christoffersen

Kupiec POF (H0: exception rate = 1 - level, chi-square 1 df); Christoffersen independence (H0: exceptions not
clustered, `n11` = consecutive exceptions) and conditional coverage (both, chi-square 2 df); pass at p >= {cfg['forecasting']['alpha']}.

{_md(bt[show])}

- Methods passing conditional coverage at 95%: {', '.join(passing.get(0.95, [])) or 'none'}; at 99%: {', '.join(passing.get(0.99, [])) or 'none'}.
- Methods passing conditional coverage at both levels: {', '.join(winners) or 'none'}.
- Closest exception count to expectation at 99%: **{closest}** ({int(b99.loc[closest, 'observed'])} observed vs {b99.loc[closest, 'expected']:.1f} expected).

![Cumulative exceptions](figures/stage6_exceptions.png)

## Basel traffic light (99% VaR, 250-day windows)

{_md(tl)}

## Expected Shortfall check (descriptive)

On days the 99% VaR is exceeded, a correct 99% ES should on average equal the realised loss (ratio near 1;
above 1 means ES understates tail losses). This is descriptive, not a formal ES backtest.

{_md(es)}

## Exceptions by sub-period

{_md(sub)}

## Limitations

- Exceptions at 99% are rare ({int(b99['expected'].iloc[0])} expected per method), so the tests have limited power,
  and six methods are tested at two levels without a multiple-testing adjustment (standard in VaR validation,
  but the chance that at least one method fails by luck is higher than 5%).
- Positions are synthetic and static in MWh.
"""
    (cfg.path("outputs_dir") / "stage6_report.md").write_text(text, encoding="utf-8")
