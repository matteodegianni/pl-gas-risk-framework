"""Stage 13 report. Every number is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage13_report(cfg: Config, t: dict[str, pd.DataFrame]) -> None:
    lim = t["limits"]
    mdl = t["model"].iloc[0]
    wwr = t["wrong_way"]
    prof = t["exposure_profile"]
    breaches = lim[lim["status"] == "breach"]
    amber = lim[lim["status"] == "amber"]
    buy_wwr = wwr[wwr["ratio_high_to_all"] > 0]
    tot = prof.groupby("month")[["ee_eur", "pfe_95_eur"]].sum()
    fan = t["price_fan"].set_index("month")
    br_text = "; ".join(f"{r.counterparty} (grade {r.grade}, utilisation {r.utilisation:.2f})" for r in breaches.itertuples()) or "none"
    am_text = "; ".join(f"{r.counterparty} ({r.utilisation:.2f})" for r in amber.itertuples()) or "none"
    text = f"""# Stage 13 - Counterparty credit risk report

Generated by `python -m gasrisk.credit`. Every number is computed. **Counterparties, financial ratios, trades and
limits are synthetic.** Exposures in EUR from the supplier's point of view.

## Model

{_md(t['model'], floatfmt="{:.6f}")}

Monte Carlo of the TTF second-month price with the refitted Stage 4 GARCH(1,1)-t (Student-t shocks, driftless), daily
steps read on a monthly grid. All delivery months move with the simulated price (no forward curve in the free data).
Price fan (multiple of today's price): at 12 months the 95% interval is {fan.loc[12, 'q2_5_x_f0']:.4f} to
{fan.loc[12, 'q97_5_x_f0']:.4f}; at 24 months {fan.loc[24, 'q2_5_x_f0']:.4f} to {fan.loc[24, 'q97_5_x_f0']:.4f}.

## Trades (synthetic)

{_md(t['trades'], floatfmt="{:,.2f}")}

## Scorecard (synthetic financial ratios)

Each ratio scores 1-5 by thresholds in `config.yaml`; the weighted score maps to an internal grade, which sets the limit
on the peak 95% PFE.

{_md(t['scorecard'], floatfmt="{:,.2f}")}

## Exposure and limits

CE = exposure today; EPE = average EE over months 1-12; netting benefit = 1 - peak netted EE / peak EE without netting.

{_md(lim, floatfmt="{:,.4f}")}

- Breaches: **{br_text}**. Amber (from {cfg['credit']['amber_threshold']:.0%}): {am_text}.
- The breach combines the weakest grade with the largest in-the-money position: its forwards were struck below
  today's price, so exposure starts high and grows with price volatility.
- Netting matters only where a counterparty has offsetting trades (CP05: peak EE
  {lim.set_index('counterparty').loc['CP05', 'netting_benefit_peak_ee']:.1%} lower with netting).
- Portfolio peak EE (sum over counterparties) {tot['ee_eur'].max():,.0f} EUR at month {int(tot['ee_eur'].idxmax())}.

Monthly profiles: `outputs/stage13_exposure_profile.csv`.

## Wrong-way risk (limitation)

The model treats exposure and default as independent. For a gas supplier this is optimistic: a counterparty that
sells gas forward to the supplier loses on that contract exactly when prices spike, which is when the supplier's
exposure to it peaks. The table shows the peak-month EE in the {cfg['credit']['wwr_top_share']:.0%} highest-price
paths against all paths.

{_md(wwr, floatfmt="{:,.4f}")}

- For the counterparties that sell to the supplier, EE in high-price paths is
  {buy_wwr['ratio_high_to_all'].min():.2f}x to {buy_wwr['ratio_high_to_all'].max():.2f}x the average. If default
  probability rises in those paths, the expected loss is larger than an independent model implies.
- Mitigants outside this model: collateral (CSA thresholds and margining), shorter tenors for weak grades, a
  stressed-PD overlay or a price-dependent PD in a future version.

## Limitations

- Single-factor price model with a flat curve; no seasonality or inter-month spreads.
- No collateral, CSA thresholds or settlement risk; delivery months drop out when delivery starts.
- PFE horizon and GARCH parameters from the last 750 days; long-horizon volatility depends on the estimated persistence
  ({mdl['persistence']:.6f}).
"""
    (cfg.path("outputs_dir") / "stage13_report.md").write_text(text, encoding="utf-8")
