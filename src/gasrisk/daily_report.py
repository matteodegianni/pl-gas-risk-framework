"""Daily risk report (Stage 16), generated from the day's output tables. Every number is computed."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_daily_report(cfg: Config) -> str:
    out = cfg.path("outputs_dir")
    official = pd.read_csv(out / "stage7_official_method.csv")["method"].iloc[0]
    v = pd.read_csv(out / "stage5_var_today.csv").set_index("method")
    lim = pd.read_csv(out / "stage7_limits_today.csv")
    amber = float(cfg["limits"]["amber_threshold"])
    lim["status"] = ["breach" if u > 1 else "amber" if u >= amber else "green" for u in lim["utilisation"]]
    tl = pd.read_csv(out / "stage6_traffic_light.csv").set_index("method").loc[official]
    st = pd.concat([pd.read_csv(out / "stage8_historical.csv"), pd.read_csv(out / "stage8_hypothetical.csv")], ignore_index=True)
    worst = st.loc[st["pnl_total"].idxmin()]
    m = pd.read_csv(out / "stage12_summary.csv").iloc[0]
    ms = pd.read_csv(out / "stage12_stress.csv")
    mw = ms.loc[ms["margin_call_eur"].idxmax()]
    cl = pd.read_csv(out / "stage13_limits.csv")
    val = pd.read_csv(out / "validation_report.csv")
    att = pd.read_csv(out / "stage9_total.csv").set_index("component")["pln"]
    as_of = v["as_of"].iloc[0]
    text = f"""# Daily risk report - {as_of}

Generated by `python -m gasrisk.pipeline`. **Synthetic book on real market data.** Every number is computed.

## Market risk

- Official 99% VaR ({official}): **{v.loc[official, 'var_99']:,.0f} PLN**; 97.5% ES {v.loc[official, 'es_97.5']:,.0f} PLN.
- Backtest: latest 250-day exceptions {int(tl['latest_250d_exceptions'])}, traffic-light zone **{tl['latest_zone']}**.

{_md(lim, floatfmt="{:,.4f}")}

## Stress

Worst scenario: {worst['scenario']}, {worst['pnl_total']:,.0f} PLN ({worst['loss_over_var99']:.2f}x the 99% VaR).

## Margin and liquidity (EUR)

- Initial margin {m['im_today_fhs_eur']:,.0f}; 10-day 99% buffer {m['buffer_10d_q99_eur']:,.0f}
  ({m['buffer_over_credit_line']:.1%} of the credit line).
- Largest stress margin call: {mw['scenario']}, {mw['margin_call_eur']:,.0f} ({mw['credit_line_utilisation']:.1%} of the line).

## Counterparty credit

{_md(cl[['counterparty', 'grade', 'ce_eur', 'peak_pfe_95_eur', 'pfe_limit_eur', 'utilisation', 'status']], floatfmt="{:,.2f}")}

## Contract P&L (since signing)

Total {att['total_pnl']:,.0f} PLN: plan margin {att['plan_margin']:,.0f}, volume {att['volume_effect']:,.0f},
price {att['price_effect']:,.0f}, FX {att['fx_effect']:,.0f}.

## Validation

{int(val['passed'].sum())} of {len(val)} checks passed; errors: {int(((~val['passed']) & (val['severity'] == 'error')).sum())}.
"""
    (out / "daily_risk_report.md").write_text(text, encoding="utf-8")
    return f"report for {as_of}"
