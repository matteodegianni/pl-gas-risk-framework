"""Generate the Stage 1 markdown report from computed tables (no hand-typed numbers)."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.quality import IssueLog


def _md(df: pd.DataFrame, floatfmt: str = "{:.4f}") -> str:
    """Render a DataFrame as a GitHub markdown table without extra dependencies."""
    if df.empty:
        return "_none_"
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append("" if pd.isna(v) else floatfmt.format(v))
            else:
                cells.append("" if v is None or (not isinstance(v, str) and pd.isna(v)) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write_stage1_report(cfg: Config, tables: dict[str, pd.DataFrame], panel: pd.DataFrame, log: IssueLog) -> None:
    """Write ``outputs/stage1_report.md``."""
    lg = log.to_frame()
    sev = lg.groupby("severity").agg(entries=("issue_id", "size"), observations=("n_obs", "sum")).reset_index()
    by_series = (lg.groupby(["series", "severity"]).size().unstack(fill_value=0).reset_index())
    actions = lg[lg["action"].str.contains("NaN|dropped|carried|replaced|weighted", regex=True)]
    act = actions.groupby(["series", "check", "action"]).agg(entries=("issue_id", "size"), observations=("n_obs", "sum")).reset_index()
    roll = tables["roll_validation"]
    panel_rows = len(panel)

    text = f"""# Stage 1 - Data and data quality report

Generated by `python -m gasrisk.data.build`. Every number below is computed by
the build; nothing is typed by hand. Raw and clean data are not committed
(licences); this report contains counts, dates and returns-based statistics only.

## Sources

{_md(tables['source_summary'])}

## Aligned panel

Calendar: TTF second-month (ICE Endex) trading days. {panel_rows} rows from
{panel.index[0].date()} to {panel.index[-1].date()}. TGE is aligned on trade date
(delivery date minus one day). Every EUR/PLN source (NBP, ECB, Yahoo) is carried
into the panel, each carried forward over its own holidays within the configured
limit; `eurpln` is the configured risk source (`fx.risk_source` =
{cfg['fx']['risk_source']}, selected in Stage 2). EUA is the latest auction price
within the configured age limit.

{_md(tables['panel_coverage'])}

## Issue log overview

Full log: `outputs/data_quality_log.csv` (one row per event or contiguous run).

{_md(sev)}

By series and severity:

{_md(by_series)}

### Entries where data were changed

Every row removed, set to missing, carried forward or replaced:

{_md(act)}

## TTF roll handling

Roll days are the first trading day after expiry (two UK business days before
the delivery month). Adjusted roll-day return = ln(c1_t / c2_t-1).

{_md(roll)}

## Return outliers

Robust z-score above {cfg['quality']['outlier_z']} on log returns, classified by a
second series (confirmed, contradicted with next-day reversal, or unconfirmed).

{_md(tables['outlier_summary'])}

## EUR/PLN cross-source comparison

{_md(tables['fx_cross_source'], floatfmt="{:.6f}")}
"""
    path = cfg.path("outputs_dir") / "stage1_report.md"
    path.write_text(text, encoding="utf-8")
