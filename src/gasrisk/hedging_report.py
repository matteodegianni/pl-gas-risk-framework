"""Stage 11 report. Every number is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage11_report(cfg: Config, t: dict[str, pd.DataFrame], h_star: float) -> None:
    h = cfg["hedging"]
    r = t["ratios"].set_index(["sample", "frequency"])
    st = t["strategies"]
    a = st[st["sample"] == "all windows"].set_index(["strategy", "eur_forward"])
    c = st[st["sample"] == "crisis windows"].set_index(["strategy", "eur_forward"])
    fr = f"futures {h['fixed_ratio']:.2f}"
    hs = f"futures h*={h_star:.3f}"
    col = f"collar {h['fixed_ratio']:.2f}"
    eff = t["effectiveness"].set_index("hedge")
    fut = eff.loc["TTF futures only"]
    k = int(h["cumulative_periods"])
    dec = t["ineffectiveness"]
    share = dec.set_index("component")["covariance_share_of_ineffectiveness_variance"]
    fail = dec.dropna(subset=["subset"]).set_index("subset")
    cost = t["cost"].set_index("strategy")
    if fut["regression_effective"]:
        reg_text = (f"The regression test **passes** (slope {fut['regression_slope']:.4f}, R2 {fut['regression_r2']:.4f} against "
                    f"a minimum of {h['regression_r2_min']}): over many periods TTF explains most of the TGE move, but "
                    "period by period the basis noise is too large for the dollar-offset band. The two tests disagree, "
                    "which is common for cross hedges; the regression test is the more stable one.")
    else:
        reg_text = (f"The regression test also fails (slope {fut['regression_slope']:.4f}, R2 {fut['regression_r2']:.4f} "
                    f"against a minimum of {h['regression_r2_min']}).")
    text = f"""# Stage 11 - Hedging and hedge effectiveness report

Generated by `python -m gasrisk.hedging`. Every number is computed. The book is **synthetic** (open volume
{cfg['book']['q_open_mwh']:,} MWh short TGE). Hedged item: TGE purchases in PLN per MWh; hedge: TTF second-month
futures (EUR), P&L per MWh in PLN = roll-adjusted TTF change x EUR/PLN. Effectiveness tests are a **simplified
illustration, not IFRS 9 hedge accounting**.

## Minimum-variance hedge ratio

h* = Cov(dS, dF) / Var(dF); `h_ttf_with_fx` and `h_fx_with_fx` are the two-instrument coefficients when an EUR forward
(per MWh, sized at TGE in EUR) is added.

{_md(t['ratios'], floatfmt="{:.4f}")}

Rolling estimates:

{_md(t['rolling_summary'], floatfmt="{:.4f}")}

- Daily changes give a full-sample h* of {r.loc[('full', 'daily'), 'h_star']:.4f} (R2 {r.loc[('full', 'daily'), 'r2']:.4f});
  21-day changes give {r.loc[('full', '21-day'), 'h_star']:.4f} (R2 {r.loc[('full', '21-day'), 'r2']:.4f}). The daily
  ratio is lower because TGE day-ahead and TTF month-ahead are asynchronous and the basis mean-reverts (Stages 2-3):
  over a month more of the TTF move passes through to TGE.
- The latest rolling 36-block ratio, **{h_star:.4f}**, is used as the "optimal" futures hedge below.
- The EUR forward adds little: R2 at 21 days moves from {r.loc[('full', '21-day'), 'r2']:.4f} to
  {r.loc[('full', '21-day'), 'r2_with_fx']:.4f}.

## Strategy comparison (today's book, 21-day horizon)

{int(a.loc[("no hedge", False), "windows"])} overlapping 21-day historical windows
({int(c.loc[('no hedge', False), 'windows'])} in the crisis window {h['crisis_window']}) applied to today's levels with
full revaluation; reductions are against no hedge without the EUR forward.

{_md(st, floatfmt="{:,.4f}")}

Cost:

{_md(t['cost'], floatfmt="{:,.6f}")}

- Variance reduction (all windows, no EUR forward): {hs} {a.loc[(hs, False), 'variance_reduction']:.1%}, {fr}
  {a.loc[(fr, False), 'variance_reduction']:.1%}, {col} {a.loc[(col, False), 'variance_reduction']:.1%}.
- 99% VaR reduction: {a.loc[(hs, False), 'var99_reduction']:.1%} ({hs}), {a.loc[(fr, False), 'var99_reduction']:.1%}
  ({fr}), {a.loc[(col, False), 'var99_reduction']:.1%} ({col}); in crisis windows only
  {c.loc[(hs, False), 'var99_reduction']:.1%}, {c.loc[(fr, False), 'var99_reduction']:.1%} and
  {c.loc[(col, False), 'var99_reduction']:.1%}: the TTF hedge reduces normal-times risk but not the TGE spike tail
  (consistent with Stage 8).
- The collar protects above the call strike and gives up savings below the put strike; between the strikes the volume
  is unhedged, which is why it removes less variance than futures. It costs a net premium of
  {cost.loc[col, 'premium_pct_F']:.4%} of F ({cost.loc[col, 'premium_eur']:,.0f} EUR, {cost.loc[col, 'premium_pln']:,.0f} PLN
  on {h['fixed_ratio']:.2f} of the volume) at the volatility assumption of Stage 10.
- Adding the EUR forward changes the variance reduction by at most
  {(st.groupby(['strategy', 'sample']).apply(lambda x: x['variance_reduction'].diff().abs().max(), include_groups=False)).max():.1%} of the no-hedge variance:
  FX is a small part of the 21-day risk of this book.

## Hedge effectiveness (21-day periods, 1:1 designated volume)

{_md(t['effectiveness'], floatfmt="{:.4f}")}

**Dollar-offset fails**: only {fut['dollar_offset_pass_rate']:.1%} of {int(fut['periods'])} periods fall inside
{h['dollar_offset_band'][0]:.0%}-{h['dollar_offset_band'][1]:.0%} with TTF futures alone; the cumulative ratio over
rolling {k}-period (one-year) relationships passes in {fut[f'rolling_{k}_period_cumulative_pass_rate']:.1%} of them.
{fut['fails_with_small_dS_share']:.1%} of the failing periods have a TGE change below the median absolute change, the
known small-denominator weakness of the ratio. {reg_text}

### Where the ineffectiveness comes from

Exact identity per MWh: dS - dF = dB_adj x FX_t + TGE_EUR_t-1 x dFX, with dB_adj the roll-adjusted change of the
TGE-TTF location plus tenor basis.

{_md(dec, floatfmt="{:.4f}")}

- The basis term carries **{share['basis term dB_adj x FX']:.1%}** of the variance of the ineffectiveness (covariance
  share; the FX term {share['FX term TGE_EUR x dFX']:.1%}).
- In failing periods the basis term is {fail.loc['failing periods', 'basis_share_of_abs_ineffectiveness']:.1%} of the
  absolute ineffectiveness ({fail.loc['passing periods', 'basis_share_of_abs_ineffectiveness']:.1%} in passing periods).
- The failure is therefore the Stage 8 finding seen from the accounting side: the TGE day-ahead vs TTF second-month
  basis, not FX and not the hedge ratio, breaks the 80-125% band. A same-tenor TGE forward or a TTF day-ahead hedge
  would be needed to pass; neither is in the free data.

## Limitations

- Simplified effectiveness tests, not IFRS 9 (no designation documentation, no hypothetical derivative).
- Collar values use the Stage 10 volatility assumption with no smile; the option tenor (Jan 2027) is held for 21 days.
- Strategy comparison replays historical joint moves on today's levels; transaction costs and margin funding are not
  included (margin in Stage 12).
"""
    (cfg.path("outputs_dir") / "stage11_report.md").write_text(text, encoding="utf-8")
