"""Stage 7 report. Every number is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage7_report(cfg: Config, tables: dict[str, pd.DataFrame], as_of: pd.Timestamp) -> None:
    lim = cfg["limits"]
    om = tables["official_method"].iloc[0]
    br = tables["breaches"]
    var_br = br[br["limit"] == "var_99"] if not br.empty else br
    drivers = var_br["main_contributor"].value_counts().to_dict() if not var_br.empty else {}
    text = f"""# Stage 7 - Limits and breach analysis report

Generated by `python -m gasrisk.limits`. Every number is computed. Book and limits are **synthetic**.

## Official VaR method

**{om['method']}**: {om['reason']} (Stage 6 backtest).

## Limits (synthetic)

| limit | value | escalation |
|---|---|---|
| 99% one-day VaR | {lim['var99_limit_pln']:,} PLN | amber from {lim['amber_threshold']:.0%}, breach above 100% |
| open gas exposure (unhedged volume x TGE price in PLN) | {lim['open_gas_exposure_limit_pln']:,} PLN | same |
| FX net open position (EUR value of TGE purchases not covered by the forward) | {lim['fx_net_open_limit_eur']:,} EUR | same |

Limits are round management numbers relative to the synthetic book, not fitted to the backtest.

## Today ({as_of.date()})

{_md(tables['limits_today'], floatfmt="{:,.4f}")}

Euler decomposition of today's official 99% VaR by risk factor (components sum to the VaR):

{_md(tables['var_components_today'], floatfmt="{:,.4f}")}

## Utilisation over the test window

{_md(tables['utilisation_summary'], floatfmt="{:,.4f}")}

![Utilisation](figures/stage7_utilisation.png)

## Breach episodes and drivers

An episode is a run of consecutive breach days. VaR driver: the main contributor (largest Euler share of the
official VaR at the start) and the factor whose component rose most over the {lim['driver_lookback_days']} trading days before the episode (`vol_ratio_*` = conditional volatility at start /
at the reference date). Exposure driver: exact split of the log change in utilisation since it was last below
amber into the TGE price and EUR/PLN parts.

{_md(br, floatfmt="{:,.4f}") if not br.empty else '_No breaches._'}

VaR breach episodes by main contributor: {', '.join(f'{k}: {v}' for k, v in drivers.items()) or 'none'}.

## Method notes and limitations

- Euler components use linear sensitivities with the official method's GARCH volatilities and copula
  correlations and are rescaled to the official (fully revalued) VaR; for large moves the linear split is an
  approximation.
- Exposure limits are value-based, so they bind when prices rise even with unchanged volumes.
- Positions are synthetic and static in MWh; breaches here are market driven by construction.
"""
    (cfg.path("outputs_dir") / "stage7_report.md").write_text(text, encoding="utf-8")
