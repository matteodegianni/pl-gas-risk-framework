"""Stage 12 report. Every number is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage12_report(cfg: Config, t: dict[str, pd.DataFrame]) -> None:
    s = t["summary"].iloc[0]
    st = t["stress"]
    hs = t["historical_summary"].set_index("sample")
    worst = st.loc[st["margin_call_eur"].idxmax()]
    m = cfg["margin"]
    n_over_buffer = int((st["margin_call_eur"] > s["buffer_10d_q99_eur"]).sum())
    hist_note = ("The excess over 1% comes from history containing volatility far above today's (crisis 99th percentile "
                 f"daily volatility {s['crisis_q99_sigma_daily']:.4f} against {s['garch_sigma_next_daily']:.4f} today): the buffer is "
                 "conditional on today's volatility and must be recomputed daily."
                 if s["hist_share_10d_vm_outflow_above_buffer"] > 1 - m["buffer_confidence"] else "")
    n_over_line = int((st["margin_call_eur"] > s["bank_credit_line_eur"]).sum())
    text = f"""# Stage 12 - Margin forecasting report

Generated by `python -m gasrisk.margin`. Every number is computed. Position: **synthetic** long
{s['position_mwh']:,.0f} MWh of TTF second-month futures (the Stage 5 hedge), notional {s['notional_eur']:,.0f} EUR on
{s['as_of']}. Margin calls are positive when cash is paid to the clearing house. The bank credit line
({s['bank_credit_line_eur']:,.0f} EUR) is a **synthetic** round number.

## Initial margin today

IM = 2-day 99% loss quantile of the long position by filtered historical simulation (GARCH(1,1) refitted on the last
{cfg['var']['garch_window']} returns, bootstrapped standardised residuals, driftless futures price).

{_md(t['summary'], floatfmt="{:,.6f}")}

- IM today: **{s['im_today_fhs_eur']:,.0f} EUR** ({s['im_today_fhs_pln']:,.0f} PLN), {s['im_today_pct_notional']:.2%} of notional; the
  closed-form approximation N x F x (1 - exp(sqrt(2) sigma q01)) gives {s['im_today_formula_eur']:,.0f} EUR.
- This is a VaR-based proxy for an exchange margin model (ICE uses its own SPAN-type parameters); the order of
  magnitude, not the exact number, is what the treasury plan needs.

## Base forecast (next {m['buffer_horizon_days']} trading days)

Cumulative margin outflow = - sum of VM + change in IM, from {m['n_paths']:,} FHS-GARCH paths.

{_md(t['forecast'], floatfmt="{:,.0f}")}

- The expected cumulative outflow over 10 days is {s['mean_cum_outflow_10d_eur']:,.0f} EUR: with a driftless price the
  mean VM is zero and IM drifts with the forecast volatility.
- **Liquidity buffer** (99% quantile of the 10-day cumulative outflow): **{s['buffer_10d_q99_eur']:,.0f} EUR**,
  {s['buffer_10d_q99_pln']:,.0f} PLN at today's EUR/PLN and {s['buffer_10d_q99_pln_fx_stress']:,.0f} PLN with EUR/PLN
  +{m['fx_stress']:.0%}; {s['buffer_over_credit_line']:.1%} of the credit line. The 99% quantile of the peak cumulative
  outflow within the 10 days is {s['peak_cum_outflow_10d_q99_eur']:,.0f} EUR.
- Historical check: {s['hist_share_10d_vm_outflow_above_buffer']:.2%} of {int(s['hist_windows_10d']):,} historical 10-day TTF moves,
  applied to today's position, produce a VM outflow above the buffer (target 1%). {hist_note}

## Stress

VM at today's position; IM recomputed after the scenario (volatility at the end of a historical episode, today's
volatility for hypothetical shocks).

{_md(st, floatfmt="{:,.4f}")}

- Largest margin call: **{worst['scenario']}**, {worst['margin_call_eur']:,.0f} EUR ({worst['margin_call_pln']:,.0f} PLN),
  {worst['credit_line_utilisation']:.1%} of the credit line.
- Scenarios above the 10-day buffer: {n_over_buffer} of {len(st)}; above the credit line: {n_over_line}.
- The Stage 8 scenarios that hurt the P&L most (TGE spikes) bring **cash in** on the long TTF hedge when TTF rises;
  the margin risk is the opposite move, a TTF collapse, as in early 2022. P&L risk and liquidity risk sit in different
  scenarios, so the treasury plan must cover both.

## Historical margin of a constant position

{_md(t['historical_summary'], floatfmt="{:,.0f}")}

At the {hs.loc['crisis window', 'date_max_im']} peak, IM on the same volume reached {hs.loc['crisis window', 'max_im_eur']:,.0f} EUR
because both price and volatility peaked; the largest 10-day cumulative call was
{hs.loc['crisis window', 'max_10d_cum_call_eur']:,.0f} EUR, {hs.loc['crisis window', 'max_10d_cum_call_eur'] / s['bank_credit_line_eur']:.2f}x the synthetic credit line.
At crisis price levels the same hedge volume would need a larger facility: the line should be sized on price and
volatility levels, not on today's notional.

## Limitations

- IM is a VaR proxy, not the ICE margin methodology; historical IM uses full-sample Stage 4 parameters and a
  2 x one-step variance approximation.
- Single TTF contract; no curve or inter-month spread credits; options (Stage 11 collar) are not included.
- PLN figures convert at today's EUR/PLN (and +5%); the EUR funding itself is the exposure.
"""
    (cfg.path("outputs_dir") / "stage12_report.md").write_text(text, encoding="utf-8")
