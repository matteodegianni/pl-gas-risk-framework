"""Stage 17: one-page management memo for the CFO and Management Board, generated from the output tables.

Usage::

    python -m gasrisk.memo

Writes ``docs/management_memo.md`` and ``outputs/stage17_memo_figures.csv`` (every figure in the memo, raw and as
printed, so ``gasrisk.doccheck`` can trace it). The hedge recommendation follows a stated rule (config ``memo``).
"""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config, load_config


def recommend(strat: pd.DataFrame, tol: float) -> pd.Series:
    """Futures strategy with the EUR forward and the highest 99% VaR reduction; prefer the lower ratio within ``tol``."""
    f = strat[(strat["sample"] == "all windows") & strat["eur_forward"] & strat["strategy"].str.startswith("futures")].copy()
    f["ratio"] = f["strategy"].str.extract(r"([0-9.]+)$").astype(float)
    best = f["var99_reduction"].max()
    near = f[f["var99_reduction"] >= best - tol]
    return near.sort_values("ratio").iloc[0]


def run(cfg: Config) -> pd.DataFrame:
    out = cfg.path("outputs_dir")
    strat = pd.read_csv(out / "stage11_strategies.csv")
    rec = recommend(strat, float(cfg["memo"]["var_reduction_tolerance"]))
    a = strat[(strat["sample"] == "all windows") & strat["eur_forward"]].set_index("strategy")
    c = strat[(strat["sample"] == "crisis windows") & strat["eur_forward"]].set_index("strategy")
    fut = [s for s in a.index if s.startswith("futures")]
    other = next(s for s in fut if s != rec["strategy"])
    collar = next(s for s in a.index if s.startswith("collar"))
    cost = pd.read_csv(out / "stage11_cost.csv").set_index("strategy")
    eff = pd.read_csv(out / "stage11_effectiveness.csv").set_index("hedge").loc["TTF futures only"]
    dec = pd.read_csv(out / "stage11_ineffectiveness.csv").dropna(subset=["component"]).set_index("component")
    v = pd.read_csv(out / "stage5_var_today.csv").set_index("method")
    off = pd.read_csv(out / "stage7_official_method.csv")["method"].iloc[0]
    lim = pd.read_csv(out / "stage7_limits_today.csv").set_index("limit")
    ref = pd.read_csv(out / "stage8_reference.csv").iloc[0]
    st = pd.concat([pd.read_csv(out / "stage8_historical.csv"), pd.read_csv(out / "stage8_hypothetical.csv")], ignore_index=True)
    worst = st.loc[st["pnl_total"].idxmin()]
    m = pd.read_csv(out / "stage12_summary.csv").iloc[0]
    ms = pd.read_csv(out / "stage12_stress.csv")
    mw = ms.loc[ms["margin_call_eur"].idxmax()]
    hs = pd.read_csv(out / "stage12_historical_summary.csv").set_index("sample").loc["crisis window"]
    r = float(pd.read_csv(out / "stage10_inputs.csv")["eur_rate_cc"].iloc[0])
    cl = pd.read_csv(out / "stage13_limits.csv")
    br = cl[cl["status"] == "breach"].iloc[0]
    att = pd.read_csv(out / "stage9_total.csv").set_index("component")["pln"]
    fx = float(m["im_today_fhs_pln"] / m["im_today_fhs_eur"])
    funding_eur = float(m["buffer_10d_q99_eur"]) * r

    F: dict[str, tuple[float, str]] = {}

    def f(key: str, value: float, fmt: str) -> str:
        s = fmt.format(value)
        F[key] = (float(value), s)
        return s

    rec_ratio = float(rec["ratio"])
    text = f"""# Management memo - gas supply risk

To: CFO and Management Board | As of {m['as_of']} | **Illustrative: synthetic book, limits and counterparties on real
market prices.** All figures are generated by the risk models (`python -m gasrisk.memo`).

**Recommendation.** Hedge with **TTF futures at {f('rec_ratio', rec_ratio, '{:.0%}')} of open volume**, with the EUR forward. Over
{int(rec['windows']):,} historical 21-day periods this cuts the worst-case (99%) loss by {f('rec_var_red', rec['var99_reduction'], '{:.1%}')}, against
{f('other_var_red', a.loc[other, 'var99_reduction'], '{:.1%}')} at the statistically optimal ratio of {other.split('=')[-1] if '=' in other else other} and
{f('collar_var_red', a.loc[collar, 'var99_reduction'], '{:.1%}')} with an options collar. The higher ratio adds no tail protection but
would raise margin needs by {f('margin_uplift', (float(other.split('=')[-1]) if '=' in other else rec_ratio) / rec_ratio - 1, '{:.0%}')}; the collar costs
{f('collar_premium_pln', cost.loc[collar, 'premium_pln'], '{:,.0f}')} PLN in option value and protects less.

**Cost of risk.** Futures carry no premium; the cost is liquidity. Holding the margin buffer of
{f('buffer_eur', m['buffer_10d_q99_eur'], '{:,.0f}')} EUR costs about {f('funding_eur', funding_eur, '{:,.0f}')} EUR a year at the current euro rate
({f('eur_rate', r, '{:.2%}')}). Today's one-day 99% value at risk is {f('var99', v.loc[off, 'var_99'], '{:,.0f}')} PLN,
{f('var_util', lim.loc['99% VaR (PLN)', 'utilisation'], '{:.0%}')} of the {f('var_limit', ref['var99_limit_pln'], '{:,.0f}')} PLN limit.

**Margin and bank line.** Exchange initial margin is {f('im_eur', m['im_today_fhs_eur'], '{:,.0f}')} EUR. In 99% of 10-day periods the
extra cash call stays below {f('buffer_eur2', m['buffer_10d_q99_eur'], '{:,.0f}')} EUR ({f('buffer_pln', m['buffer_10d_q99_pln'], '{:,.0f}')} PLN),
{f('buffer_line', m['buffer_over_credit_line'], '{:.0%}')} of the {f('line', m['bank_credit_line_eur'], '{:,.0f}')} EUR bank line. The
worst stress, a repeat of the {mw['from']} to {mw['to']} TTF collapse, would call {f('stress_call', mw['margin_call_eur'], '{:,.0f}')} EUR,
{f('stress_line', mw['credit_line_utilisation'], '{:.0%}')} of the line. Margin risk comes when gas prices **fall**, the opposite of
the P&L risk. At 2022 price levels the same hedge would have needed {f('crisis_line', hs['max_10d_cum_call_eur'] / m['bank_credit_line_eur'], '{:.1f}')}x
the line in 10 days: the line should be reviewed if prices rise.

**Key risks.**
1. **Polish price spikes.** The Dutch TTF hedge does not follow Polish day-ahead spikes. The worst historical
   scenario would lose {f('worst_loss', -worst['pnl_total'], '{:,.0f}')} PLN, {f('worst_x', -worst['pnl_total'] / ref['var_99'], '{:.0f}')} times today's
   value at risk; in crisis periods the hedge cuts the worst-case loss by only {f('crisis_red', c.loc[rec['strategy'], 'var99_reduction'], '{:.0%}')}.
   This basis explains {f('basis_share', dec.loc['basis term dB_adj x FX', 'covariance_share_of_ineffectiveness_variance'], '{:.0%}')} of the
   hedge's misses.
2. **Hedge accounting.** The hedge passes the month-by-month offset test in only {f('do_pass', eff['dollar_offset_pass_rate'], '{:.0%}')} of
   months, so reported P&L would stay volatile under hedge accounting without a Polish-price hedge.
3. **Exposure limits.** Higher gas prices have pushed open gas exposure to {f('gas_util', lim.loc['open gas exposure (PLN)', 'utilisation'], '{:.0%}')}
   and the FX open position to {f('fx_util', lim.loc['FX net open position (EUR)', 'utilisation'], '{:.0%}')} of their limits.
4. **Counterparty.** {br['counterparty']}, the weakest-rated counterparty, uses {f('cp_util', br['utilisation'], '{:.0f}')} times its exposure
   limit; exposures to gas sellers rise when prices spike, when they are weakest.

**Decisions requested.** (1) Approve the {F['rec_ratio'][1]} futures hedge policy. (2) Approve a plan for the two exposure-limit
breaches. (3) Require collateral or a lower tenor from {br['counterparty']}. (4) Ask treasury to confirm the bank line covers the
{F['stress_call'][1]} EUR stress call.

Contract P&L since signing: {f('contract_pnl', att['total_pnl'], '{:,.0f}')} PLN against a plan of {f('plan', att['plan_margin'], '{:,.0f}')} PLN.
"""
    (cfg.root / "docs" / "management_memo.md").write_text(text, encoding="utf-8")
    figs = pd.DataFrame([{"figure": k, "value": v[0], "printed": v[1]} for k, v in F.items()])
    figs.to_csv(out / "stage17_memo_figures.csv", index=False)
    return figs


def main() -> None:
    print(run(load_config()).to_string(index=False))


if __name__ == "__main__":
    main()
