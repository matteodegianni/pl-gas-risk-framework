"""Stage 10 report. Every number is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage10_report(cfg: Config, t: dict[str, pd.DataFrame]) -> None:
    inp = t["inputs"].iloc[0]
    ref, par, fd, grid = t["reference"], t["parity"], t["fd_greeks"], t["grid"]
    atm = grid[grid["moneyness_K_over_F"] == 1.0].set_index("kind")
    vs = t["vol_sensitivity"]
    vs_call = vs[vs["kind"] == "call"].set_index("vol_source")["atm_value_pct_F"]
    vols = t["vol_assumptions"].set_index("vol_source")["sigma_annual"]
    fd_max = fd.groupby("greek")["rel_diff"].max().rename("max_rel_diff").reset_index()
    text = f"""# Stage 10 - Black-76 option pricing report

Generated by `python -m gasrisk.pricing`. Every number is computed. Option values are **model values under a volatility
assumption, not market prices**: there is no free TTF implied volatility data. Values are shown as a share of the
futures price F (Black-76 is homogeneous in F and K), so no raw TTF price level is published.

## Inputs

{_md(t['inputs'], floatfmt="{:.6f}")}

- Underlying: the TTF second-month future held in the Stage 5 book; option expiry follows the ICE Endex rule (5
  calendar days before the delivery month, prior UK business day if needed); ACT/365 time to expiry.
- Rate: ECB euro area AAA spot curve interpolated to expiry ({inp['eur_rate_cc']:.4%}). ICE Endex TTF options are
  futures-style margined, so the exchange value is not discounted and the rate only matters for premium-paid OTC
  options (shown separately).

## Volatility assumption

{_md(t['vol_assumptions'], floatfmt="{:.6f}")}

The pricer uses **{inp['vol_source_used']}** ({inp['sigma_annual']:.4f} annualised). The ATM call value is
{vs_call['garch_t']:.4%} of F with GARCH-t, {vs_call['hist_63d']:.4%} with 63-day historical volatility and
{vs_call['ewma']:.4%} with EWMA: the choice of volatility moves the value by
{(vs_call.max() - vs_call.min()):.4%} of F, which is the size of this model risk.

{_md(vs, floatfmt="{:.6f}")}

## Validation

**Published reference examples** (premium-paid Black-76):

{_md(ref, floatfmt="{:.6f}")}

All examples match the published value at the published rounding: **{bool(ref['matches_published_rounding'].all())}**.

**Put-call parity** C - P = DF (F - K) on the strike grid, futures-style (DF = 1) and premium-paid: maximum absolute
error {par['abs_error_pct_F'].max():.3e} of F.

**Finite-difference Greeks** (central differences, relative bump {cfg['pricing']['fd_bump_rel']}):

{_md(fd_max, floatfmt="{:.3e}")}

**Implied volatility round trip**: maximum error {grid['implied_vol_roundtrip_error'].max():.3e}.

## Option grid (futures-style, {inp['vol_source_used']} volatility)

Values and vega as a share of F; vega per 1 volatility point; theta per calendar day.

{_md(grid, floatfmt="{:.6f}")}

ATM call: value {atm.loc['call', 'value_pct_F']:.4%} of F, delta {atm.loc['call', 'delta']:.4f}; ATM put delta
{atm.loc['put', 'delta']:.4f}. Futures-style deltas of a call and a put with the same strike differ by exactly 1.

Premium-paid (discounted) grid: `outputs/stage10_grid_premium_paid.csv`.

## Limitations

- The volatility input is a time-series forecast, not an implied volatility; there is no smile or skew, so OTM option
  values (the collar wings in Stage 11) are likely understated relative to a market with a call skew in a crisis.
- The underlying is a single futures price; no forward curve is available from free sources.
- European exercise only (ICE Endex TTF options are European).
"""
    (cfg.path("outputs_dir") / "stage10_report.md").write_text(text, encoding="utf-8")
