"""Stage 8 report. Every number is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def write_stage8_report(cfg: Config, tables: dict[str, pd.DataFrame]) -> None:
    ref = tables["reference"].iloc[0]
    hist, hyp = tables["historical"], tables["hypothetical"]
    allsc = pd.concat([hist[["scenario", "pnl_total"]], hyp[["scenario", "pnl_total"]]], ignore_index=True)
    worst = allsc.loc[allsc["pnl_total"].idxmin()]
    best = allsc.loc[allsc["pnl_total"].idxmax()]
    sens = tables["sensitivities"].set_index("scenario")["pnl_total"]
    n_over_limit = int((-allsc["pnl_total"] > ref["var99_limit_pln"]).sum())
    rs = tables["reverse_stress"]
    text = f"""# Stage 8 - Stress testing and sensitivity report

Generated by `python -m gasrisk.stress`. Every number is computed. Book is **synthetic**; P&L in PLN, positions and
levels as of {ref['as_of']}; every scenario fully revalued (TGE leg -Q x (TGE_EUR' x FX' - TGE_EUR x FX), TTF leg
N x (TTF' - TTF) x FX', FX leg N_fx x (FX' - FX)).

Reference: official 99% VaR ({ref['official_method']}) {ref['var_99']:,.0f} PLN; 97.5% ES {ref['es_97.5']:,.0f} PLN;
VaR limit {ref['var99_limit_pln']:,.0f} PLN.

## Sensitivities

{_md(tables['sensitivities'], floatfmt="{:,.0f}")}

P&L per +1 PLN/MWh TGE: {sens['+1 PLN/MWh TGE']:,.0f} PLN; per +1 EUR/MWh TTF: {sens['+1 EUR/MWh TTF']:,.0f} PLN;
per +0.01 EUR/PLN: {sens['+0.01 EUR/PLN']:,.0f} PLN.

Larger moves (full revaluation):

{_md(tables['sensitivity_grid'], floatfmt="{:,.0f}")}

## Historical scenarios (2021-2022 crisis, applied to today's book)

Worst k-day joint moves for today's book inside {cfg['stress']['crisis_window']} and named episodes; `move_*` are
relative changes over the window.

{_md(hist, floatfmt="{:,.4f}")}

## Hypothetical scenarios

{_md(hyp, floatfmt="{:,.4f}")}

`TTF +50% only` moves the hedge without the physical exposure, i.e. a large basis compression; the hedged book
gains. The gas-complex scenarios move both legs together.

## Reverse stress

{_md(rs, floatfmt="{:,.4f}")}

## Summary

- Worst scenario: **{worst['scenario']}** ({worst['pnl_total']:,.0f} PLN, {-worst['pnl_total'] / ref['var_99']:.2f}x today's 99% VaR).
- Best scenario: {best['scenario']} ({best['pnl_total']:+,.0f} PLN).
- Scenarios with a loss above the VaR limit: {n_over_limit} of {len(allsc)}.
- In the worst historical window TGE (EUR) moved {hist.loc[hist['pnl_total'].idxmin(), 'move_tge_eur']:+.1%} and TTF
  {hist.loc[hist['pnl_total'].idxmin(), 'move_ttf']:+.1%}; the TGE leg accounts for
  {hist.loc[hist['pnl_total'].idxmin(), 'pnl_tge_leg'] / hist.loc[hist['pnl_total'].idxmin(), 'pnl_total']:.1%} of the loss. The month-ahead TTF hedge does
  not follow TGE day-ahead spikes: this is the location plus tenor basis, amplified by valuing unhedged future
  purchases at the day-ahead price.
- The book is short TGE and long TTF, so it loses when TGE rises relative to TTF (basis widening) and when the gas
  complex rises (the hedge covers {cfg['book']['ttf_hedge_ratio']:.0%} of the volume); a TTF rally alone helps it.

## Limitations

- Historical scenarios replay factor moves on today's positions and levels; liquidity and margin effects are in Phase 2.
- Unhedged future purchases are valued at TGE day-ahead (location plus tenor basis).
"""
    (cfg.path("outputs_dir") / "stage8_report.md").write_text(text, encoding="utf-8")
