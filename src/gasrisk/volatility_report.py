"""Stage 4 report. Every number and verdict is computed from the tables."""

from __future__ import annotations

import pandas as pd

from gasrisk.config import Config
from gasrisk.data.report import _md


def _mean_text(sel: pd.DataFrame, lb: pd.DataFrame, lb_cols: list[str], alpha: float) -> str:
    lines = []
    for r in sel.itertuples(index=False):
        g = lb[lb["series"] == r.series].set_index("model")
        before = g.loc["constant mean (before)", lb_cols]
        ar1 = g.loc["AR(1)", lb_cols]
        after = g.loc["selected (after)", lb_cols]
        fmt = lambda s: ", ".join(f"{v:.4f}" for v in s)  # noqa: E731
        ar1_ok = bool((ar1 >= alpha).all())
        lines.append(
            f"- **{r.series}**: selected mean **{r.mean}** ({r.mean_reason}). Ljung-Box p on standardised residuals "
            f"at lags {', '.join(c.split('p')[-1] for c in lb_cols)}: constant mean {fmt(before)}; AR(1) {fmt(ar1)} "
            f"({'passes' if ar1_ok else 'does not pass'}); selected {fmt(after)}. "
            f"Selection on the first training window only: {r.mean_selected_on_first_window} "
            f"({'same' if r.same_on_first_window else 'different'})."
        )
    return "\n".join(lines)


def _dist_text(fit: pd.DataFrame, sel: pd.DataFrame) -> str:
    lines = []
    for r in sel.itertuples(index=False):
        g = fit[fit["series"] == r.series].set_index("dist")
        cells = "; ".join(f"{d}: BIC {g.loc[d, 'bic']:.1f}, below 1% {g.loc[d, 'share_below_q01']:.4f}, "
                          f"above 99% {g.loc[d, 'share_above_q99']:.4f}" for d in g.index)
        lines.append(f"- **{r.series}**: selected **{r.dist}** ({r.dist_reason}). {cells}.")
    return "\n".join(lines)


def _oos_verdicts(ev: pd.DataFrame, bench: str) -> str:
    lines = []
    for (s, h), g in ev.groupby(["series", "h"], sort=False):
        best = g.loc[g["qlike"].idxmin()]
        better = g[g["verdict_qlike"] == "better than benchmark (Holm)"]["model"].tolist()
        raw = g[g["verdict_qlike"] == "better (raw only)"]["model"].tolist()
        lines.append(f"- {s}, h={h}: lowest QLIKE **{best['model']}**; better than {bench} after Holm: "
                     f"{', '.join(better) or 'none'}" + (f"; raw only: {', '.join(raw)}" if raw else "") + ".")
    return "\n".join(lines)


def _persistence_text(fit: pd.DataFrame, sel: pd.DataFrame) -> str:
    lines = []
    for r in sel.itertuples(index=False):
        f = fit[(fit["series"] == r.series) & (fit["dist"] == r.dist)].iloc[0]
        if f["near_integrated"]:
            lines.append(f"- {r.series}: persistence {f['persistence']:.4f}, **near-integrated** (at or above 0.999): shocks "
                         "barely decay and a half-life is not meaningful; the model behaves much like EWMA.")
        else:
            lines.append(f"- {r.series}: persistence {f['persistence']:.4f}, half-life {f['half_life_days']:.1f} days.")
    return "\n".join(lines)


def write_stage4_report(cfg: Config, tables: dict[str, pd.DataFrame]) -> None:
    v = cfg["volatility"]
    alpha = float(v["alpha"])
    sel, fit, ev, lb = tables["selected_spec"], tables["garch_fit"], tables["vol_forecast_eval"], tables["lb_before_after"]
    lb_cols = [f"lb_z_p{L}" for L in v["lb_lags"]]
    fit_cols = ["series", "mean", "dist", "n", "loglik", "aic", "bic", "ar_coefs", "alpha", "beta", "nu", "skew_lambda",
                "persistence", "near_integrated", "half_life_days"]
    diag_cols = ["series", "mean", "dist", *lb_cols, "lb_z2_p10", "arch_lm_z_p5", "z_excess_kurtosis", "pit_ks_p",
                 "share_below_q01", "share_below_q05", "share_above_q95", "share_above_q99", "calib_error_1pct"]
    ev_cols = ["series", "h", "model", "n", "qlike", "qlike_diff_vs_bench", "dm_p_qlike", "holm_p_qlike", "mse_ratio_vs_bench",
               "dm_p_mse", "verdict_qlike"]
    mz = ev[ev["h"] == 1][["series", "model", "mz_a", "mz_b", "mz_b_se", "mz_b_eq_1_p", "mz_r2"]]
    chosen = fit.merge(sel[["series", "dist"]], on=["series", "dist"])
    oos1 = ev[(ev["h"] == 1) & ev["model"].str.startswith("garch")]

    text = f"""# Stage 4 - Volatility report

Generated by `python -m gasrisk.volatility`. Every number and verdict is computed; nothing is typed by hand.

## Design

- **Series:** TTF (roll-adjusted, two excluded roll days dropped), TGE, EUR/PLN (ECB) as percent log returns;
  the location plus tenor basis (TGE day-ahead spot minus TTF second month) as daily changes in EUR/MWh.
- **Mean equation:** candidates {', '.join(d['name'] for d in v['mean_candidates'])} (AR lags and/or day-of-week
  dummies), fitted with GARCH(1,1)-t. Rule: keep the constant mean if its standardised residuals pass Ljung-Box
  at lags {v['lb_lags']} (p >= {alpha}); otherwise the lowest-BIC candidate that passes. Stage 5 filtered historical
  simulation resamples these standardised residuals, so they must be serially uncorrelated.
- **Innovations:** normal and Student-t for every series, plus {', '.join(f"{k}: {', '.join(x)}" for k, x in v.get('extra_distributions', {}).items())};
  chosen by BIC and by two-sided tail calibration at 1% (share of residuals below the fitted 1% quantile and above
  the 99% quantile, both expected at 0.0100).
- **Out-of-sample:** rolling {v['train_window']}-day window, re-estimation every {v['refit_every']} trading days, daily filter
  updates; cumulative variance forecasts at h = {v['horizons']} account for the AR mean. Benchmarks: EWMA
  (lambda {v['ewma_lambda']}) and a {v['rolling_window']}-day rolling variance. Realised variance proxy: summed squared
  returns; MSE and QLIKE losses (Patton 2011); DM vs {v['benchmark']} (HAC h-1 lags, HLN) with Holm adjustment.

## 1. Selected specification

{_md(sel)}

## 2. Mean equation and residual autocorrelation

Ljung-Box p-values on GARCH-t standardised residuals before (constant mean), with AR(1), and after selection:

{_md(lb)}

{_mean_text(sel, lb, lb_cols, alpha)}

All candidates (GARCH-t):

{_md(tables['mean_selection'])}

## 3. Innovation distribution

{_md(fit[fit_cols])}

Standardised residual diagnostics (selected mean equation):

{_md(fit[diag_cols])}

{_dist_text(fit, sel)}

Persistence of the selected models:

{_persistence_text(fit, sel)}

![Conditional volatility](figures/stage4_conditional_vol.png)

## 4. Out-of-sample volatility forecasts

Test window:

{_md(tables['test_window'])}

{_md(ev[ev_cols])}

`qlike_diff_vs_bench` below zero means lower (better) QLIKE than {v['benchmark']}; `mse_ratio_vs_bench` below one means lower MSE.

{_oos_verdicts(ev, v['benchmark'])}

### Mincer-Zarnowitz (h = 1): realised = a + b x forecast

{_md(mz)}

An unbiased, efficient forecast has a = 0 and b = 1. Squared daily returns are a noisy proxy, so low R^2 is
expected even for a good model; the slope is the informative part.

## 5. Implications for VaR (Stage 5)

- In-sample tail calibration of the selected models (expected 0.0100 in each tail):
  {', '.join(f"{r.series} ({r.dist}) below 1% {r.share_below_q01:.4f}, above 99% {r.share_above_q99:.4f}" for r in chosen.itertuples(index=False))}.
- Out-of-sample GARCH at h=1 relative to {v['benchmark']}: {', '.join(f"{r.series} {r.model} QLIKE diff {r.qlike_diff_vs_bench:+.4f}" for r in oos1.itertuples(index=False))}.
- Stage 5 uses the selected mean equation and distribution for GARCH VaR, the selected model's standardised
  residuals for filtered historical simulation, and EWMA (never beaten out of sample) as a separate VaR method.

## Limitations

- Realised variance is proxied by squared daily returns; intraday data would give a sharper proxy.
- Symmetric GARCH(1,1) only; leverage or inverse-leverage effects (GJR, EGARCH) are not modelled.
- The mean equation is selected on the full sample; the first-window check above shows whether the same choice
  would have been made without future data.
- Persistence at or near one is also what unmodelled structural breaks (such as the 2021-2022 crisis regime)
  produce; a regime-switching or break-adjusted GARCH is out of scope.
- The basis is a location plus tenor basis whose large moves come mainly from TGE spot spikes (Stage 2).
"""
    (cfg.path("outputs_dir") / "stage4_report.md").write_text(text, encoding="utf-8")
